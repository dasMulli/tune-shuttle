    /// The reply to one <c>/fp-setup</c> body (SPEC-receiver.md R14), or null when shairport-sync could not build one either
    /// (too short, an unknown sequence byte or a mode above 3) [sps:rtsp.c:1946-1948]. A wrong version or type byte is only
    /// logged by shairport-sync [sps:rtsp.c:1920-1922]; <paramref name="unsupportedVersion"/> reports it.
    /// </summary>
    /// <param name="request">The request body.</param>
    /// <param name="unsupportedVersion">True when the version byte is not 3 or the type byte not 1.</param>
    public static byte[]? Reply(ReadOnlySpan<byte> request, out bool unsupportedVersion)
    {
        unsupportedVersion = request.Length <= TypeOffset || request[VersionOffset] != 3 || request[TypeOffset] != 1;
        if (request.Length <= SequenceOffset)
        {
            return null;
        }

        switch (request[SequenceOffset])
        {
            case 1:
                if (request.Length <= ModeOffset)
                {
                    return null;
                }

                return request[ModeOffset] switch
                {
                    0 => Reply1.ToArray(),
                    1 => Reply2.ToArray(),
                    2 => Reply3.ToArray(),
                    3 => Reply4.ToArray(),
                    _ => null,
                };
            case 3:
                if (request.Length < Setup2SuffixLength)
                {
                    return null;
                }

                var reply = new byte[Setup2Header.Length + Setup2SuffixLength];
                Setup2Header.CopyTo(reply, 0);
                request[^Setup2SuffixLength..].CopyTo(reply.AsSpan(Setup2Header.Length));
                return reply;
            default:
                return null;
        }
    }
